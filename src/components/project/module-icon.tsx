export type IconName = keyof typeof icons;

export function ModuleIcon({ name, className = "size-5", ...rest }: { name: IconName; className?: string } & React.SVGProps<SVGSVGElement>) {
  const Icon = icons[name];
  return <Icon className={className} strokeWidth={1.6} aria-hidden="true" {...rest} />;
}
